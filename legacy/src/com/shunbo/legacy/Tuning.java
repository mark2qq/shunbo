package com.shunbo.legacy;

/**
 * 闭环阈值集中表（研发计划 PQ-1 / M2）。
 *
 * <p><b>为什么单独一个类</b>：M2 的四个闭环（A1 假高清 / B1 带宽塌陷 /
 * D2 时钟偏快 / 以及沿用 1.0.2 的 6 秒快失败、15 秒看门狗、60 秒 3 次卡顿）
 * 各自有一到三个阈值。散落在各处时，M1 标定回来要改一个数得找五个文件；
 * 集中在这里之后，「调参」是一处改动、一处评审。
 *
 * <p><b>每个常量后面都写了「依据」</b>：标了「实测」的来自 2026-11-10 乐视
 * S50 Air（API 18 / 1920×1080 / 1512 MB）真机诊断页读数；标了「经验」的
 * 是还没有真机分布支撑的保守取值，M1 补齐分布后必须回填。这条纪律是为了
 * 防止半年后没人知道某个 0.4 是哪来的。
 *
 * <p>本类不持有状态、不读偏好，纯常量表，任何线程读都安全。
 */
final class Tuning {

    private Tuning() {}

    // ================================================================
    // A1 假高清：只判断「实测宽度是否够得上标称」，不用码率
    // ================================================================

    /**
     * 实测宽度低于「标称宽度 × 该比例」即判为假高清。
     *
     * <p><b>依据（实测）</b>：M1 两张真机截图——标称 1080P 的线路实测
     * 1920×1080、码率仅 1.95 Mbps；另一条 800×600 的线路码率 0.56 Mbps。
     * 若按码率判（旧设 1.5 Mbps），1.95 Mbps 的**真** 1080P 会被误判成假的，
     * 降权后用户反而被推到更糊的线路上。宽度是解码器直出的硬读数，
     * 不受分片突发影响，所以判据只用宽度。
     *
     * <p>0.75 的含义：1080P 要 ≥1440 宽（1280×720 冒充 1080 判假）、
     * 720P 要 ≥960 宽（800×600 冒充 720 判假）、576P 要 ≥540 宽。
     * 留 25% 余量是为了让 1440×1080（4:3 变形源）之类不算假。
     */
    static final float FAKE_HD_WIDTH_RATIO = 0.75f;

    // ================================================================
    // B1 带宽塌陷：相对本线路自身的基线，不看绝对值
    // ================================================================

    /**
     * 基线窗口。
     *
     * <p><b>依据（实测）</b>：真机上流量折算码率 1080P 约 1.95 Mbps、
     * 标清约 0.56 Mbps，跨台差 3.5 倍；用固定绝对值当阈值必然一头误报一头失灵。
     * 30 秒足以跨过 10 个 3 秒分片，又短于一次广告 / 片头切换。
     */
    static final int BW_BASE_WINDOW_SAMPLES = 30;

    /**
     * 快窗口：判「现在是不是在塌」。
     *
     * <p>8 秒 ≈ 2～3 个分片。再短会被分片拉取的锯齿打穿（拉一段、停一段，
     * 单采样瞬时码率可以掉到 0），再长则滞后于用户观感。
     */
    static final int BW_FAST_WINDOW_SAMPLES = 8;

    /**
     * 快窗口低于基线的这个比例，判「塌陷」。
     *
     * <p><b>经验值</b>：HLS 分片拉取本身有 ±30% 的锯齿，45% 以下才算真的
     * 掉速而不是抓取节奏。M1 若采到更细的分布应回填。
     */
    static final float BW_COLLAPSE_RATIO = 0.40f;

    /**
     * 基线低于这个码率就不做塌陷判断。
     *
     * <p>标清线路本来就只有 0.5 Mbps 上下（实测 0.56），此时「跌 60%」是
     * 噪声而不是事件；而且这么低的码率就算真跌了，换线收益也抵不上打断。
     */
    static final long BW_MIN_BASE_BPS = 400000L;

    /** 连续几次采样都判塌陷才动手；约合 3 秒。 */
    static final int BW_COLLAPSE_SAMPLES = 3;

    /** 两次「塌陷换线」之间的冷却，防止在新线路上立刻再触发一次。 */
    static final long BW_COOLDOWN_MS = 60000L;

    // ================================================================
    // D2 音频时钟偏快
    // ================================================================

    /**
     * 播放位置增速比超过它即「音频在快播」。
     *
     * <p><b>依据（实测）</b>：真机 1080P 台读数为 1.000（3 个窗口），
     * 说明这台机器上没有系统性偏差。阈值取 2%，是「1.000 的读数要连续两个
     * 窗口明显越界」才动手，避免把一次窗口抖动当成故障。
     */
    static final double SYNC_FAST_RATE = 1.02;

    /** 连续两个 10 秒窗口都越界才动手（约 20 秒观测）。 */
    static final int SYNC_FAST_WINDOWS = 2;

    /** 两次「时钟换线」之间的冷却。 */
    static final long SYNC_COOLDOWN_MS = 45000L;

    // ================================================================
    // D3 播放停滞（画面几乎不动）
    // ================================================================

    /**
     * 播放位置增速低于它即「停滞」。
     *
     * <p><b>依据（实测）</b>：10:31 的真机读数抓到一次 **0.169**——10 秒里只推进
     * 1.7 秒，同时缓存 280 ms、音频 0 ms、码率读不到，而「最近 60 秒缓冲」只有
     * **1 次**。也就是说它既没有持续缓冲事件（15 秒看门狗不触发），画面也确实
     * 停在那儿。这正是「有保护但全都没踩到」的空档。
     *
     * <p>0.5 的含义：正常直播 0.99～1.01，轻微卡顿 0.9 上下，低于 0.5 已经是
     * 「一半以上的时间在等数据」，不存在正常场景。
     */
    static final double STALL_RATE = 0.50;

    /** 连续两个 10 秒窗口都停滞才动手（约 20 秒），避免一次分片抖动误判。 */
    static final int STALL_WINDOWS = 2;

    /**
     * 判停滞的**第二个必要条件**：视频缓存必须已经见底。
     *
     * <p><b>依据（实测，10:58 证否）</b>：只看「位置增速」的版本在真机上出过一次
     * **0.004**——同一时刻视频缓存 **13040 ms**、码率 3.18 Mbps、丢帧 0.5%。
     * 一个真冻住的流不可能还攒着 13 秒缓存并持续收 3 Mbps；那是直播源
     * `getCurrentPosition()` 在分片边界重置造成的读数假象。
     * 若照旧判，会在好线路上「治好了卡顿、换来了黑屏」。
     *
     * <p>对照样本：10:31 那次真实的停滞是 0.169 + 缓存 **280 ms** + 音频 0 ms +
     * 零流量。两次读数的区别就在缓存上，所以用它当必要条件。
     * 1000 ms 的含义：低于 1 秒缓存时，画面还能撑不到一秒。
     */
    static final long STALL_MAX_CACHE_MS = 1000L;

    /** 停滞处置的冷却：换线与「单线路重连」都受它约束，防止连环重连。 */
    static final long STALL_COOLDOWN_MS = 30000L;

    // ================================================================
    // 质量巡检
    // ================================================================

    /**
     * 巡检周期。探针本身是 1 秒采样，这里只决定「多久看一次环形缓冲」。
     *
     * <p>2 秒：比 1 秒省一次无谓判断，又不至于让 3 采样判据（3 秒）失真太多。
     */
    static final long QUALITY_WATCH_MS = 2000L;

    // ================================================================
    // D4 手动「音画立即对齐」
    // ================================================================

    /**
     * 手动再锚的冷却。
     *
     * <p><b>为什么是手动而不是自动</b>：原本想用「视频缓存 − 音频缓存」当触发条件，
     * 但两份真机读数直接矛盾——11:06 的样本差 **+14152 ms** 而用户**没有**觉得不同步，
     * 12:19 苏州台1套差 **+2440 ms** 用户明确说「画面延迟」。同一个量一大一小却给出
     * 相反结论，说明它不可解释（视频侧是解码帧队列，音频侧只是包队列，两者口径不同）。
     * 用一个不可解释的量去自动 seek，就是在好画面上做实验。
     *
     * <p>所以先给一个**用户按了下去就有反馈**的动作：按一次，画面跳到与声音对齐的
     * 位置。如果按了确实好，说明病因就是 frame_timer 相位，届时再谈自动化。
     */
    static final long REANCHOR_COOLDOWN_MS = 3000L;

    /**
     * 换台时等「后台释放队列排空」的上限（ms）。
     *
     * <p><b>依据（实测）</b>：16:48 真机 31.jpg 的「释放」行——重叠 83 次 /
     * 起播 86 次（96.5%）、最近队列 3 个、上次释放仅 62 ms、现存待释放 0 个。
     * 也就是说释放**并不慢、也不会长期堆积**，但几乎每次换台新 player 都在
     * 旧 player 还没释放完时绑到同一个 SurfaceHolder。200 ms 足够单线程串行
     * 排空 3 个（3×62≈186 ms），又远小于同页真机出画 720 ms；**超时就照常
     * 继续**，绝不阻塞换台。
     *
     * <p>这不是「凭嫌疑盲改释放时序」：§43 当时不动它是因为担心拖慢换台，
     * 而这组真机读数把代价钉在了 62 ms 量级。等待有硬上限、有诊断读数、
     * 旧包可一键回退，是一个可证伪的干预——消掉重叠后若仍发病，
     * 嫌疑 A 当场排除。
     */
    static final long RELEASE_DRAIN_TIMEOUT_MS = 200L;

    /** 内部用：bps → Mbps 文案，诊断与失败原因共用，避免两处格式化不一致。 */
    static String mbps(long bps) {
        if (bps <= 0L) return "—";
        return String.format(java.util.Locale.US, "%.2f", bps / 1000000.0);
    }
}
